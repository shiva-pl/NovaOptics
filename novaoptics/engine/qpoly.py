"""Forbes Q-type polynomials for strong aspheres (Forbes, Opt. Express 15, 5218 (2007)).

Surface types follow the OpticStudio "Q-Type Asphere" numbering:

* type 0, **Qbfs** (best-fit sphere): departure measured from a sphere along its normal,
  slope-orthogonal basis::

      z = c r^2 / (1 + sqrt(1 - c^2 r^2))
          + u^2 (1 - u^2) / sqrt(1 - c^2 r^2) * sum_m a_m Q^bfs_m(u^2),   u = r / r_norm

  with  int_0^1 P_m'(u) P_n'(u) / sqrt(1 - u^2) du = (pi/2) delta_mn,
  P_m(u) = u^2 (1 - u^2) Q^bfs_m(u^2), and the sign fixed by Q^bfs_m(0) > 0.

* type 1, **Qcon** (conic plus sag-orthogonal departure)::

      z = c r^2 / (1 + sqrt(1 - (1 + k) c^2 r^2)) + u^4 sum_m a_m Q^con_m(u^2)

  with Q^con_m(x) = P^(0,4)_m(2x - 1) (Jacobi polynomials).

Q^bfs is generated by orthonormalizing Chebyshev polynomials in t = 2x - 1 (well
conditioned) and evaluated with the Chebyshev recurrence; Q^con with the Jacobi
three-term recurrence.
"""

from __future__ import annotations

import jax.numpy as jnp
import numpy as np
from numpy.polynomial import chebyshev as Ch

MAX_TERMS = 20


def _qbfs_chebyshev(m_max=MAX_TERMS):
    """Coefficients C[m, j] with Q^bfs_m(x) = sum_j C[m, j] T_j(2x - 1)."""
    th, w = np.polynomial.legendre.leggauss(400)  # u = sin(theta), theta in (0, pi/2)
    th = (th + 1) * np.pi / 4
    w = w * np.pi / 4
    u = np.sin(th)
    # d/du [u^2 (1-u^2) T_j(2u^2-1)] / sqrt(1-u^2) * du/dtheta = ... * cos(th) / cos(th)
    x = u * u
    D = []
    for j in range(m_max):
        cj = np.zeros(j + 1)
        cj[-1] = 1.0
        T = Ch.chebval(2 * x - 1, cj)
        dT = Ch.chebval(2 * x - 1, Ch.chebder(cj)) * 2.0  # d/dx
        # d/du [x (1 - x) T(x)] = 2u [(1 - 2x) T + x (1 - x) T']
        D.append(2 * u * ((1 - 2 * x) * T + x * (1 - x) * dT))
    D = np.array(D)
    G = (D * w) @ D.T / (np.pi / 2)  # weight 1/sqrt(1-u^2) cancels du/dtheta = cos(theta)
    L = np.linalg.cholesky(G)
    C = np.linalg.inv(L)  # rows: orthonormal combinations
    t0 = np.array([Ch.chebval(-1.0, np.eye(m_max)[j]) for j in range(m_max)])  # T_j(-1)
    C = C * np.sign(C @ t0)[:, None]  # Q_m(0) > 0
    return C


QBFS = _qbfs_chebyshev()


def _cheb_T(t, n):
    """T_0..T_{n-1}(t), stacked on axis 0."""
    T = [jnp.ones_like(t), t]
    for _ in range(2, n):
        T.append(2 * t * T[-1] - T[-2])
    return jnp.stack(T[:n])


def qbfs(x, n):
    """Q^bfs_0..Q^bfs_{n-1} at x (any shape), stacked on axis 0."""
    if n == 0:
        return jnp.zeros((0,) + jnp.shape(x))
    T = _cheb_T(2 * x - 1, max(n, 2))[:n]
    return jnp.tensordot(jnp.asarray(QBFS[:n, :n]), T, axes=1)


def qcon(x, n):
    """Q^con_0..Q^con_{n-1}(x) = P^(0,4)_m(2x - 1), stacked on axis 0."""
    if n == 0:
        return jnp.zeros((0,) + jnp.shape(x))
    t = 2 * x - 1
    a, b = 0.0, 4.0
    P = [jnp.ones_like(t), 0.5 * ((a + b + 2) * t + (a - b))]
    for m in range(2, n):
        k = m - 1  # P_{k+1} from P_k, P_{k-1}
        c1 = 2 * (k + 1) * (k + a + b + 1) * (2 * k + a + b)
        c2 = (2 * k + a + b + 1) * (a * a - b * b)
        c3 = (2 * k + a + b) * (2 * k + a + b + 1) * (2 * k + a + b + 2)
        c4 = 2 * (k + a) * (k + b) * (2 * k + a + b + 2)
        P.append(((c2 + c3 * t) * P[-1] - c4 * P[-2]) / c1)
    return jnp.stack(P[:n])
